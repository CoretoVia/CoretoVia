import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * КОРЕНЪТ ИДВА ОТВЪН · инак мярката не се доказва.
 *
 * Доказващият тест вдига НАРОЧНО счупено дърво във временна папка и пуска тази
 * команда срещу него. Без този вход проверката би трябвало да пише в дървото на
 * проекта — точно онова, което обход И забранява (и което улови на 09.09).
 */
const KOREN = process.env['REGISTAR_KOREN'] ?? '.';
const REGISTAR = join(KOREN, 'docs/registar-na-vaprosite.json');
const PAPKI = ['docs', 'zadanie'].map((p) => join(KOREN, p)).filter((p) => existsSync(p));

/**
 * Белегът на въпрос · видът отпред, буквата е ТЕМАТА, числото е номерът в нея.
 * `ВП-Т12` · `ВП-А3`. Голото „Т12" вече не е въпрос (2.0б); `ИН-` · `ДЛ-` · `ИЗ-` са
 * други домове и тук не се събират.
 */
const BELEG = /(?<![\p{L}\p{N}-])ВП-([ТАБВГДЕОСМФУПК]\d{1,3})(?![\p{L}\p{N}])/gu;

/**
 * Думите, с които документ обявява, че ЧАКА него.
 *
 * Стеснено на 09.09.2026: първата версия ловеше голото „негова дума" и даваше
 * тринайсет лъжливи находки — изречения като „**затворени с негова дума**" и
 * „осем са, и това е негова дума" ПОТВЪРЖДАВАТ отговор, а не го искат.
 *
 * Проверка, която вика при вярното, се изключва след третия път и тогава не
 * пази нищо. Затова тук стои ЧАКАНЕТО, не думата „дума".
 *
 * РАЗШИРЕНО на 09.09.2026 с ЕДИН нов вид, платен с негово недоволство:
 * в таблиците на дълга чакането се пише като КЛЕТКА — `| **негова дума**` —
 * без глагол. Т14 стоеше така, регистърът го броеше за отговорен, и аз пак
 * го попитах. Негово: „**Не ме занимавай с глупости, а си прочети
 * домашното.**" Голото „негова дума" остава пропуснато (тринайсетте лъжливи
 * находки); хваща се само подчертаната клетка след `|` или `·`, която НЕ може
 * да значи друго освен „това чака него".
 *
 * Подчертаването трябва да СВЪРШВА веднага след думите (или след „по Т3“),
 * инак се лови и потвърждението „**негова дума — ВЕЧЕ Е ДАДЕНА**“, което е
 * обратното на чакане. Проверено на място: то стои в chasti/7 ход 2.
 */
const CHAKA =
  /чака(т)? (негова|неговата) дума|ЧАКА НЕГОВА ДУМА|чака(т)? него\b|(без|няма|иска|липсва) негова дума|не се строи без нея|чака(т)? отговор|[|·]\s*\*\*негова дума(\s+по\s+\S+)?\*\*/u;

/**
 * Кои папки НЕ се съдят за „пита отговореното" · и защо.
 *
 * `arhiv` · приключеното (правило 13) — то нарочно пази стария си вид.
 * `izvori` · неговите думи, както са казани — те не питат, те отговарят.
 * `dokladi` · ЗАПИСИ от проверка в определен ден. Доклад, който казва „това
 *   чакаше негова дума", е ВЯРЕН за деня си; поправен задна дата, той престава
 *   да е доклад. Живият дълг обаче се съди — той твърди за ДНЕС.
 *
 * Белезите в тях СЕ БРОЯТ (за да няма въпрос без дом); само проверка 3 ги
 * подминава.
 */
const NE_SE_SADYAT = ['arhiv', 'izvori', 'dokladi', 'dnevnik'];

function vsichkiFaylove(papka, sabrani = []) {
  for (const ime of readdirSync(papka)) {
    const pat = join(papka, ime);
    if (statSync(pat).isDirectory()) {
      vsichkiFaylove(pat, sabrani);
    } else if (ime.endsWith('.md')) sabrani.push(pat.replace(/\\/g, '/'));
  }
  return sabrani;
}

/**
 * ГОЛИТЕ ДУМИ · без украсата на markdown.
 *
 * Документите носят удебеляване ВЪТРЕ в цитатите („Стопанин и Служител не се
 * сливат**, но просто **всички са Служители"), а регистърът пази чистия цитат.
 * Сравнението на голи думи гледа СМИСЪЛА, не форматирането — инак машината би
 * валила заради две звездички.
 */
function goli(t) {
  return t.replace(/[*_`]/gu, '').replace(/\s+/gu, ' ').trim();
}

/** Съди ли се този файл за „пита нещо вече отговорено"? */
function sesadi(f) {
  return !NE_SE_SADYAT.some((p) => f.includes(`/${p}/`));
}

function chetiRegistara() {
  try {
    return JSON.parse(readFileSync(REGISTAR, 'utf8'));
  } catch {
    return { vaprosi: [] };
  }
}

/** Всеки белег на въпрос (`ВП-X`), срещнат в документите · с файловете, в които стои. */
function belezitéVDokumentite(faylove) {
  const kade = new Map();
  for (const f of faylove) {
    for (const m of readFileSync(f, 'utf8').matchAll(BELEG)) {
      if (!kade.has(m[1])) kade.set(m[1], new Set());
      kade.get(m[1]).add(f);
    }
  }
  return kade;
}

const faylove = PAPKI.flatMap((p) => vsichkiFaylove(p));
const kade = belezitéVDokumentite(faylove);
const reg = chetiRegistara();
const po = new Map(reg.vaprosi.map((v) => [v.beleg, v]));

if (process.argv.includes('--sazday')) {
  // от 11.09.2026 (2.0в) не ражда записи · обвивка без въпрос не е въпрос · непознат
  // `ВП-X` е находка на `--proveri`, а въпросът се вписва с ръка и с текста си
  let osvezheni = 0;
  for (const v of reg.vaprosi) {
    const novo = [...(kade.get(v.beleg) ?? [])].sort();
    if (JSON.stringify(novo) !== JSON.stringify(v.zhivee_v ?? [])) osvezheni += 1;
    v.zhivee_v = novo;
  }
  reg.vaprosi.sort((a, b) => a.beleg.localeCompare(b.beleg, 'bg'));
  writeFileSync(REGISTAR, `${JSON.stringify(reg, null, 2)}\n`, 'utf8');
  const nepoznati = [...kade.keys()].filter((b) => !po.has(b)).sort();
  console.log(
    `Регистър · видени ${faylove.length} файла · ${kade.size} белега ВП- · освежени ${osvezheni} записа · непознати ${nepoznati.length}${
      nepoznati.length > 0 ? ` (${nepoznati.join(' · ')}) — вписват се с ръка, с въпроса си` : ''
    }`,
  );
  process.exit(0);
}

// ─────────────────────────────── ПРОВЕРКА ───────────────────────────────────
const nahodki = [];

// 1 · нула непознати
for (const [beleg, gde] of kade) {
  if (!po.has(beleg))
    nahodki.push(`1 · непознат белег „${beleg}" · стои в ${[...gde].join(' · ')}`);
}

// 2 · отговореното носи неговите думи, и те стоят на адреса си
for (const v of reg.vaprosi) {
  if (v.sastoyanie !== 'otgovoren') continue;
  if (v.negovite_dumi.trim() === '') {
    nahodki.push(`2 · „${v.beleg}" е отговорен без НЕГОВИ думи`);
    continue;
  }
  if (v.adres.trim() === '') {
    nahodki.push(`2 · „${v.beleg}" носи думи без адрес`);
    continue;
  }
  /**
   * Адресът често носи ПОВЕЧЕ от един файл („docs/10:128 · zadanie/05:60") и
   * понякога започва с дума („Цитат 05.09: …"). Затова тук се вадят ВСИЧКИ
   * файлове от него и цитатът се търси във всеки: стои ли поне в един, опората
   * е налице. Инак машината би валила заради формата на записа, не заради
   * липсваща опора — а тя пази опората.
   */
  const faylove = [...v.adres.matchAll(/[\w./\\-]+\.(?:md|ts|mjs|json|cjs)/gu)].map((m) =>
    m[0].replace(/\\/g, '/').replace(/^.*Coretovia\//u, ''),
  );
  if (faylove.length === 0) {
    nahodki.push(`2 · „${v.beleg}" няма файл в адреса си: ${v.adres.slice(0, 80)}`);
    continue;
  }
  /**
   * ЦИТАТЪТ, не обвивката му.
   *
   * Записът често носи и наша дума пред него („Не се иска поправка. Дословно,
   * както стои: „…""). Сверява се НЕГОВОТО — най-дългото, което стои в кавички.
   * Няма ли кавички, взима се целият запис.
   */
  const vKavichki = [...v.negovite_dumi.matchAll(/„([^“”"]{10,})[“”"]/gu)].map((m) => m[1]);
  const suroviyat =
    vKavichki.length > 0 ? vKavichki.sort((a, b) => b.length - a.length)[0] : v.negovite_dumi;
  const parche = goli(suroviyat).slice(0, 40);
  let namereno = false;
  let chetoh = false;
  for (const f of faylove) {
    let tekst = '';
    try {
      tekst = readFileSync(join(KOREN, f), 'utf8');
    } catch {
      continue;
    }
    chetoh = true;
    if (goli(tekst).includes(parche)) {
      namereno = true;
      break;
    }
  }
  if (!chetoh) {
    nahodki.push(`2 · „${v.beleg}" сочи файлове, които ги няма: ${faylove.join(' · ')}`);
  } else if (!namereno) {
    nahodki.push(`2 · думите на „${v.beleg}" ги няма в ${faylove.join(' · ')}`);
  }
}

// 5 · думите му имат ЕДИН дом · адресът на отговорен въпрос сочи в изворите или в Книгата
/*
 * Етап 1.2 (11.09.2026 · решение 1.2 от плана на 10.09). Дотук думите му живееха
 * на девет места и отговорите сочеха към `docs/10` и към записи 16–30; 10.09 и
 * 11.09 ги свалиха по дни в `docs/izvori/dni/`. Отсега опората на всеки отговорен
 * въпрос е поне един файл в ДОМА НА ДУМИТЕ МУ: `docs/izvori/**` (изворите и дните)
 * или `zadanie/00–12` (Книгата и допълненията към нея — негови клетки и думи).
 * Адрес само към решение, доклад или код не е опора: там думите му са преразказ.
 */
const DOMAT_NA_DUMITE = /^(?:docs\/izvori\/|zadanie\/(?:0\d|1[0-2])-)/u;
for (const v of reg.vaprosi) {
  if (v.sastoyanie !== 'otgovoren' || v.adres.trim() === '') continue;
  const faylove = [...v.adres.matchAll(/[\w./\\-]+\.(?:md|ts|mjs|json|cjs)/gu)].map((m) =>
    m[0].replace(/\\/g, '/').replace(/^.*Coretovia\//u, ''),
  );
  if (faylove.length > 0 && !faylove.some((f) => DOMAT_NA_DUMITE.test(f))) {
    nahodki.push(
      `5 · думите на „${v.beleg}" нямат дом: адресът сочи само ${faylove.join(' · ')} · домът им е docs/izvori/** или zadanie/00–12`,
    );
  }
}

// 3 · никой не пита отговореното · само в ЖИВИТЕ документи
for (const f of faylove.filter(sesadi)) {
  for (const [i, red] of readFileSync(f, 'utf8').split('\n').entries()) {
    /**
     * ЦИТИРАНОТО ЧАКАНЕ НЕ Е ЧАКАНЕ.
     *
     * Ред, който казва „Т17 стои под „ЧАКА НЕГОВА ДУМА" — а думата Е дадена",
     * ЦИТИРА чуждо чакане, за да го обори. Той е ПОПРАВКАТА, не дефектът.
     *
     * Затова кавичките се махат ПРЕДИ проверката: остава онова, което самият
     * документ твърди за себе си. Платено на 09.09.2026 с две лъжливи находки.
     */
    const bezTsitati = red.replace(/„[^“”"]*[“”"]/gu, ' ');
    if (!CHAKA.test(bezTsitati)) continue;
    for (const m of red.matchAll(BELEG)) {
      const beleg = m[1];
      const v = po.get(beleg);
      if (v !== undefined && v.sastoyanie === 'otgovoren') {
        // един и същи белег може да стои два пъти в реда · находката е ЕДНА
        const n = `3 · ${f}:${i + 1} пита „${beleg}", а той ИМА отговор (${v.adres})`;
        if (!nahodki.includes(n)) nahodki.push(n);
      }
    }
  }
}

// 4 · обхватът се обявява
/*
 * Състоянията НЕ се изброяват тук с ръка (правило 14): броят се от самия
 * регистър. Стоеше твърд списък от четири, а в данните живееха шест — тоест
 * два вида въпроси не се виждаха в отчета. Числото се БРОИ, не се преписва.
 */
const broy = {};
for (const v of reg.vaprosi) broy[v.sastoyanie] = (broy[v.sastoyanie] ?? 0) + 1;

