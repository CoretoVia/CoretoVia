import { describe, expect, it } from 'vitest';
import { denNaMeseca, dvanaysetMeseca } from '../src/smetach/kalendar.js';

describe('денят на месеца', () => {
  it('месецът става ПЪРВИЯ си ден · там пада ред без своя дата', () => {
    expect(denNaMeseca('2026-09')).toBe('2026-09-01');
    expect(denNaMeseca('2026-01')).toBe('2026-01-01');
  });

  it('празният месец не измисля ден', () => {
    expect(denNaMeseca('')).toBe('');
  });
});

describe('дванайсетте месеца', () => {
  it('свършват в ПОКАЗАНИЯ месец и почват единайсет месеца преди него', () => {
    expect(dvanaysetMeseca('2026-09')).toEqual({ ot: '2025-10-01', do: '2026-09-30' });
  });

  it('прескачат годината назад · и знаят колко дни има краят', () => {
    expect(dvanaysetMeseca('2026-01')).toEqual({ ot: '2025-02-01', do: '2026-01-31' });
    expect(dvanaysetMeseca('2026-02')).toEqual({ ot: '2025-03-01', do: '2026-02-28' });
  });

  it('високосният февруари е с ден повече · и той се БРОИ, не се предполага', () => {
    expect(dvanaysetMeseca('2028-02').do).toBe('2028-02-29');
  });
});
