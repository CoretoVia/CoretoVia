import type { Kesh } from './smetki.js';

export interface Trezorat {
  readonly mesets: string;
  /** цели центове · изтеглено − дадено · излезли от банката, още нераздадени */
  readonly vKasa_st: number;
  /** цели центове · дадено − вкарано · раздадени, още неосчетоводени */
  readonly vRatse_st: number;
  /** думите под числата · какво значи всяко */
  readonly formulaNaKasata: string;
  readonly formulaNaRatsete: string;
}

export function trezorat(kesh: Kesh): Trezorat {
  return {
    mesets: kesh.mesets,
    vKasa_st: kesh.izvlechenie - kesh.dadeno,
    // ВКАРАНОТО СЕ ЧЕТЕ ПО МОДУЛ · то е сборът на двете кеш секции, а те са
    // РАЗХОД и се пазят с минус (правило 16). Без модула изваждането се обръща
    // в събиране и трезорът показва двойно. Същият капан вече е затворен на
    // едно място по-горе: сверката „дадено ↔ вкарано" също взима модула.
    vRatse_st: kesh.dadeno - Math.abs(kesh.vkarano),
    formulaNaKasata: 'изтеглено по извлечение − дадено · излезли от банката, още нераздадени',
    formulaNaRatsete: 'дадено − вкарано по редовете · раздадени, още неосчетоводени',
  };
}
