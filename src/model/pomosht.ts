/**
 * ПОМОЩТА · обяснението, което живее ПРИ нещото (правило 31).
 *
 * Две части, една истина: `zashto` — защо съществува полето, бутонът, колоната
 * или прозорецът, с наши думи; `kratko` — формулата с думи („площ × база по
 * вид"), а за нещо, което не се смята — какво се пише в него. Двете СТЕПЕНИ не
 * са два свободни текста, а два изгледа върху едните части:
 *
 *   · Начало   → защо + формулата (подробното · за човек, който тепърва опознава
 *                програмата);
 *   · Нормален → само формулата (съкратеното · когато работата е позната).
 *
 * Негово, 10.09 (запис 132): „обясненията при задържане някъде да се появяват с
 * твои думи правилна и подробна информация при избор на начален HELP и съкратена
 * информация при нормален HELP." Съкратеното е ЧАСТ от подробното — затова се
 * ИЗВЕЖДА, а не се пише втори път (правило 14: един факт, един дом).
 *
 * Неговите 42 изречения от Книгата (`dumi-ot-knigata.ts`) са ИЗВОР за тези
 * текстове, не текст за екрана (запис 151: „използвай моите текстове за теб да ги
 * разбереш"). `tests/podskazkite.test.ts` пази, че нито един текст тук не е
 * негово изречение.
 *
 * Полето `pomosht` е ЗАДЪЛЖИТЕЛНО навсякъде, където го има: празна подсказка е
 * сив бутон, който не обяснява (правило 12), а незадължително поле е дупка,
 * която никой не вдига. Затова и фабриката отказва празни части — на място,
 * при строежа на Модела, не на екрана.
 */

/** Степента · латински ключ в кода и в паметта на екрана · етикетът е отделно. */
export type StepenNaPomoshtta = 'nachalo' | 'normalno';

export const STEPENI_NA_POMOSHTTA: readonly StepenNaPomoshtta[] = Object.freeze([
  'nachalo',
  'normalno',
]);

/**
 * Етикетите на степените · неговите думи: „начален HELP" · „нормален HELP"
 * (запис 132) и „Начален хелп и нормален." (запис 19). Етикетът може да се смени с негова дума;
 * ключът в кода и в паметта — не (`ui.v1.` вдига версия при смяна на формата).
 */
export const IMENATA_NA_STEPENITE: Readonly<Record<StepenNaPomoshtta, string>> = Object.freeze({
  nachalo: 'Начало',
  normalno: 'Нормален',
});

/** Новото устройство е начинаещо · подробното е подразбраното (запис 132). */
export const STEPEN_PO_PODRAZBIRANE: StepenNaPomoshtta = 'nachalo';

export interface Pomosht {
  /** защо съществува · с наши думи · едно-две изречения */
  readonly zashto: string;
  /** формулата с думи, или какво се пише тук · едно изречение · без точка накрая */
  readonly kratko: string;
}

/** Двете части се изчистват от външни интервали · празна част е отказ на място. */
function chastta(kakva: 'zashto' | 'kratko', tekst: string): string {
  const chist = tekst.normalize('NFC').trim();
  if (chist === '') {
    throw new TypeError(`Помощта няма „${kakva}" · празна подсказка е мълчание.`);
  }
  return chist;
}

/** Единствената фабрика · всяка `pomosht` в Модела и каталога минава оттук. */
export function pomosht(zashto: string, kratko: string): Pomosht {
  return Object.freeze({ zashto: chastta('zashto', zashto), kratko: chastta('kratko', kratko) });
}

/** Текстът за екрана според степента · Начало = защо + формулата · Нормален = формулата. */
export function tekstNaPomoshtta(p: Pomosht, stepen: StepenNaPomoshtta): string {
  return stepen === 'nachalo' ? `${p.zashto} · ${p.kratko}` : p.kratko;
}

/** Прочетеното от паметта на екрана е ли степен · счупен запис пада към подразбраното. */
export function eStepen(x: unknown): x is StepenNaPomoshtta {
  return x === 'nachalo' || x === 'normalno';
}
