/**
 * КОЛОНАТА · какво е една колона на таблица, като ДАННИ (ADR-003).
 *
 * Видът живее в КОЛОНАТА, не в цифрата (ADR-014 на MasterBook, пренесен).
 * Оттук се извежда всичко останало: кой СЛОТ носи клетката в събитието, как
 * се показва, влиза ли в сбор, как се пише в Книгата.
 */

import { type Pomosht, pomosht } from './pomosht.js';
import type { VidStoynost } from './vid-stoynost.js';

/**
 * Видът на колоната · петте вида стойност плюс три, които са ВРЪЗКИ, не стойности:
 *
 *   · `izbor`       — падащо меню от номенклатура · клетката пази НОМЕРА на стойността;
 *   · `vrazka`      — ред от друга таблица (Обект → Имот) · клетката пази id-то му;
 *   · `nomeratsiya` — сметнатата номерация (`3.1.1.27`) · ЗАТВОРЕНА, никой не я пише.
 */
export type VidKolona = VidStoynost | 'izbor' | 'vrazka' | 'nomeratsiya';

/**
 * СТРАНАТА на един ред с пари · приходът е +, разходът е − (правило 16).
 * Колоната, която носи секция, казва на коя страна е тя; знакът на сумата и
 * страната на секцията ТРЯБВА да си съответстват, и това е предусловие.
 */
export type Strana = 'prihod' | 'razhod';

/**
 * СТРАНАТА на плащането в продажба · по банка или в кеш.
 *
 * Неговите глави я казват с различни думи в двете таблици („ПД смр" и „ПД кеш"
 * са едно и също), затова страната е БЕЛЕГ, а думата остава негова (правило 21).
 */
export type StranaNaPlashtane = 'banka' | 'kesh';

/** НАШАТА дума за всяка страна · за екрана и за помощта · един дом, до типа си. */
export const IMENA_NA_STRANITE_NA_PLASHTANE: Readonly<Record<StranaNaPlashtane, string>> =
  Object.freeze({ banka: 'банка', kesh: 'кеш' });

/** Слотът в събитието · ТОЧНО един на клетка · по вида на колоната. */
export type Slot = 'tekst' | 'chislo' | 'stoynost_st' | 'nomer';

export interface Kolona {
  readonly klyuch: string;
  /** главата · дословно както е в Книгата, или НАША дума, ако Книгата я няма */
  readonly ime: string;
  readonly vid: VidKolona;
  /**
   * ОБЯСНЕНИЕТО ПРИ ЗАДЪРЖАНЕ · защо съществува колоната и формулата ѝ с думи
   * (`pomosht.ts`). ЗАДЪЛЖИТЕЛНО, за да пада компилацията при липса: колона без
   * обяснение е сив бутон, който не казва защо е сив.
   */
  readonly pomosht: Pomosht;
  /** ключът на номенклатурата · само при `izbor` */
  readonly nomenklatura?: string;
  /**
   * таблиците, към които може да сочи · само при `vrazka` · коя точно казва
   * ПРЕФИКСЪТ на id-то (`imot:` · `obekt:` · `biznes:`), защото `idNaRed` го носи;
   * Обектът сочи само Имот (`['imoti']`), Задачата — Имот, Обект или Бизнес
   */
  readonly vrazka?: readonly string[];
  /**
   * Връзка, която САМО СОЧИ · не прави реда ДЕТЕ на посочения.
   *
   * Отговорникът на задача сочи човек, но задачата не е негово дете: човек, който
   * напуска, се изключва, а задачите му остават и се КАЗВАТ (ADR-009). Без този
   * белег правилото „ред с живи деца не се изключва" би заключило всеки служител,
   * който носи макар една задача, и съобщението („изключи първо тях") би било
   * грешен съвет — вярното е да им дадеш друг отговорник.
   */
  readonly samoSochi?: true;
  /** за `izbor` с номерация по белег · кой белег се взима от коя колона на същия ред */
  readonly belegOt?: string;
  /** колоната носи СЕКЦИЯ на тази страна · точно една такава колона е пълна на ред */
  readonly strana?: Strana;
  /**
   * ПЛАЩАНЕТО в една продажба · какво е колоната и от коя СТРАНА.
   *
   * Неговият лист Продажби държи две страни — по банка и в кеш („смр") — и за
   * всяка: цената, вноските (ПД · НС · Акт 15 · Акт 16) и ПРОВЕРКАТА, която в
   * Книгата е формула. Тук проверката се СМЯТА: цена − сбор на вноските, и се
   * записва като сверка, дори когато е нула (правило 7). Двете му таблици имат
   * различни глави за едно и също нещо, затова смятането върви по БЕЛЕГА, не по
   * името (ADR-010).
   */
  readonly plashtane?: {
    readonly rolya: 'tsena' | 'vnoska' | 'proverka';
    readonly strana: StranaNaPlashtane;
  };
  /**
   * ВНОСКАТА, без която продажбата не е ЗАВЪРШЕНА · негово, 05.09: Акт 16.
   *
   * Остатъкът нула значи ПЛАТЕНА; завършена е онази, при която и този акт е
   * дошъл. Двете не се сливат: платена без Акт 16 е нормално състояние, което
   * се КАЗВА, а не грешка (правило 12).
   */
  readonly zavarshva?: true;
  readonly zadalzhitelna: boolean;
  /** затворена = сметка или пренесено · не се редактира от никого (правило 18) */
  readonly zatvorena: boolean;
  /** мярката на числото · кв. см за площ; иначе цяло число */
  readonly merka?: 'kvsm';
  /** думата ни е, не негова · за износа и за Заданието (правило 17) */
  readonly nashaDuma?: boolean;
  /** кратка дума за разписките и екрана, когато главата му е дълга · главата остава негова */
  readonly kratko?: string;
  /**
   * КЛЮЧЪТ на ред без номерация · тези колони заедно казват „същият ред ли е":
   * задачата е родител · вид · име · начало; движението — родител · име · секция ·
   * функция · месец. Изрично, не по „задължителна": иначе Оценката щеше да влезе
   * в ключа на задачата, а сумата — в ключа на движението (поправката щеше да
   * ражда нов ред вместо да поправя стария).
   */
  readonly vKlyucha?: true;
}

/**
 * Кой слот носи клетката · ПО ВИД, без да пита затворена ли е колоната.
 *
 * Двата въпроса са различни и се сляха в един до 10.09.2026: „каква стойност
 * НОСИ тази колона" и „може ли някой да ѝ ПИШЕ". Слети, затворената колона
 * оставаше без стълб — и вчерашният ред, който има стойност в нея, чупеше
 * сгъването. А правило 18 казва обратното: колоната се СКРИВА, скритото пак
 * се смята.
 *
 * Намерено от изискването на десетия тип (`docs/28` §2.2): затвориш ли колона
 * днес, вчерашният ред трябва да оцелее.
 */
export function slotPoVida(k: Kolona): Slot | undefined {
  switch (k.vid) {
    case 'evro':
      return 'stoynost_st';
    case 'chislo':
    case 'protsent':
      return 'chislo';
    case 'izbor':
      return 'nomer';
    case 'tekst':
    case 'data':
    case 'vrazka':
      return 'tekst';
    case 'nomeratsiya':
      return undefined;
  }
}

/**
 * Кой слот се ПИШЕ · `undefined` за затворените.
 *
 * Това е въпросът на Вратата и на регистъра: „приема ли се стойност тук".
 * За „каква стойност носи колоната" виж `slotPoVida`.
 */
export function slotNaKolonata(k: Kolona): Slot | undefined {
  return k.zatvorena ? undefined : slotPoVida(k);
}

/** Колоната влиза ли в сбор · само еврото (правило 3 · ADR-014). */
export function vlizaVSbor(k: Kolona): boolean {
  return k.vid === 'evro' && !k.zatvorena;
}

/**
 * ПОМОЩТА НА КОЛОНА, РОДЕНА ОТ ЖУРНАЛА · по вида ѝ.
 *
 * Колона, добавена от Настройки (десетият тип събитие), няма автор на текст:
 * никой не е седял да напише защо съществува. Празна подсказка не се допуска,
 * затова тя получава онова, което видът ѝ казва със сигурност — какво се пише
 * в нея и какво се смята под нея. Главата влиза в текста, за да не звучат
 * всички добавени колони еднакво.
 */
export function pomoshtNaKolonaPoVida(vid: VidKolona, ime: string): Pomosht {
  const glava = `Колона „${ime}", добавена от Настройки, не от Книгата.`;
  switch (vid) {
    case 'tekst':
      return pomosht(
        `${glava} Държи думи и нищо не се смята от тях; под нея се броят редовете и различните стойности.`,
        'свободен текст · пише се, не се смята',
      );
    case 'chislo':
      return pomosht(
        `${glava} Държи цяло число; под нея се предлагат сбор, средно, най-малко, най-голямо и брой.`,
        'цяло число · пише се · сборът под колоната е върху видимите редове',
      );
    case 'protsent':
      return pomosht(
        `${glava} Държи процент; проценти не се сборуват — под нея се смятат средно, най-малко, най-голямо и брой.`,
        'процент · пише се · под колоната се смята средно, не сбор',
      );
    case 'evro':
      return pomosht(
        `${glava} Държи сума в евро, в цели центове; знакът казва страната — плюс е приход, минус е разход.`,
        'сума в евро · пише се · влиза в сбора под колоната',
      );
    case 'data':
      return pomosht(
        `${glava} Държи дата от календара; нищо не се смята от нея.`,
        'дата от календара · година-месец-ден',
      );
    case 'izbor':
      return pomosht(
        `${glava} Държи една стойност от своята номенклатура; клетката пази номера ѝ, така преименуване от Настройки не мести редове.`,
        'избор от номенклатурата ѝ · клетката пази номера на стойността',
      );
    case 'vrazka':
      return pomosht(
        `${glava} Сочи ред от друга таблица; клетката пази ключа на реда, а на екрана се показва името му.`,
        'връзка към ред от друга таблица · избира се от списъка ѝ',
      );
    case 'nomeratsiya':
      return pomosht(
        `${glava} Номерът на реда се смята от описанието на таблицата и никой не го пише.`,
        'смята се от сегментите на таблицата · не се пише',
      );
  }
}
