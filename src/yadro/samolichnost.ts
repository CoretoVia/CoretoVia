/**
 * САМОЛИЧНОСТТА · свой ключ на устройството · и адресът, който той дава.
 *
 * Решението е ADR-024 §1, вариант 1: устройството прави двойка **Ed25519 през
 * `crypto.subtle`** — нула байта библиотека. Публичният ключ е номерът на
 * писача; Google се добавя ОТГОРЕ, като удобство за вход, не като носител.
 *
 * ═══ ЗАЩО ТОЗИ ФАЙЛ Е В ЯДРОТО, А КРИПТОГРАФИЯТА — НЕ ═══
 *
 * Същият образец като `hash.ts`: тук стои ДОГОВОРЪТ, а реализациите живеят в
 * `src/nositel/` (`samolichnost-web.ts`). Ядрото внася само ядро
 * (`.dependency-cruiser.cjs`), тъй че договорът трябва да е тук — инак
 * `pravata.ts` не може да го назове.
 *
 * ═══ ПРОВЕРЕНО, НЕ ПРЕДПОЛОЖЕНО · 08.09.2026 ═══
 *
 * Преди да се напише ред, Ed25519 през `crypto.subtle` беше пуснат в четири
 * среди:
 *
 *   Node 24.20              ✔ ключ · подпис 64б · проверка · частният НЕ се изнася
 *   Chromium 152 · localhost ✔ публичен ключ 32 байта
 *   Chromium 152 · 127.0.0.1 ✔
 *   Chromium 152 · file://   ✔  ← това решава спора
 *
 * Последният ред е важен: ADR-024 избра този вариант ЗАЩОТО работи и в
 * локалния пакет, който по конструкция няма мрежа (`connect-src 'none'`).
 * Доводът издържа проверка — `file://` е сигурен контекст в Chromium и
 * `crypto.subtle` е там.
 *
 * ═══ АДРЕСЪТ Е ВЕЧЕН · затова носи ВЕРСИЯ ═══
 *
 * Ключът на веригата влиза в Журнала, а Журналът е само за добавяне
 * (правило 1). Веднъж написан адрес НЕ МОЖЕ да се преименува — може само да
 * се замрази и да се почне нов. Затова отпечатъкът носи белега `k1-`:
 * смени ли се някога алгоритъмът, новите адреси се различават от старите на
 * око, вместо да се гадае по дължина.
 *
 * ═══ ЗАЩО НЕ ЗАПОЧВА С `coretovia` ═══
 *
 * Това е цялата причина отпечатъкът да е отпечатък. `izpalnitel.ts` чете
 * `verigi(prefiks)`, а обхватът по префикс (`dnevnik-indexeddb.ts`) хваща
 * ВСИЧКО, което започва с него. Верига на име `coretovia~…~lichno` попада
 * вътре и служебното Огледало я сгъва — точно затова ADR-024 §2 отхвърли
 * този вид ключ. Адрес, който започва с `k1-`, е ИЗВЪН обхвата по
 * конструкция, не по настройка.
 *
 * ═══ ЗАЩО ОТПЕЧАТЪК, А НЕ ИМЕЙЛ ═══
 *
 * ADR-024 §2: „инак при смяна на домейн ключът се мени и веригата остава без
 * писач." Плюс закон: отпечатък на публичен ключ не е личен данен, а
 * `sha256(имейл)` е ПСЕВДОНИМИЗИРАН личен данен по GDPR — в непроменим запис
 * разликата е голяма.
 *
 * ═══ КАКВО ТОЗИ ФАЙЛ НЕ ПРАВИ ═══
 *
 * `actor` НЕ става етикет и НЕ се сменя (ADR-024 §1, поправка от скептика):
 * `hash.ts` носи измерване, че износ със сменен само `actor` минаваше като
 * цяла верига, затова `actor` е В ПОДПИСА. Самоличността е ВТОРИ, непрозрачен
 * носител ДО имейла, не вместо него.
 */

/** Отпечатъкът на публичния ключ · `k1-` и 32 шестнайсетични знака. */
export type Otpechatak = string;

/**
 * Портът · какво умее една самоличност.
 *
 * Няма метод за изнасяне на ЧАСТНИЯ ключ, и това е нарочно: двойката се прави
 * с `extractable: false`, тоест браузърът сам отказва. „Ключът не напуска
 * устройството" е липса на метод, не обещание — същата мисъл като К3.
 */
export interface Samolichnost {
  /** Отпечатъкът · номерът на писача. Стабилен за живота на ключа. */
  otpechatak(): Promise<Otpechatak>;
  /** Публичният ключ · суров, 32 байта. За да може друг да провери подписа. */
  publichenKlyuch(): Promise<Uint8Array>;
  /** Подписва байтове · връща 64 байта. */
  podpishi(kakvo: Uint8Array): Promise<Uint8Array>;
}

/**
 * Проверка на ЧУЖД подпис · не иска своя ключ.
 *
 * Отделен тип, а не метод на `Samolichnost`: проверяващият няма самоличност
 * в тази работа. Слее ли се с интерфейса, всеки, който иска само да провери,
 * трябва първо да си направи ключ — а това е точно обратното на смисъла.
 */
export type ProveriPodpis = (
  publichen: Uint8Array,
  kakvo: Uint8Array,
  podpis: Uint8Array,
) => Promise<boolean>;

/** Белегът на версията · първата буква на всеки отпечатък. */
export const BELEG_NA_OTPECHATAK = 'k1-';

/**
 * Колко шестнайсетични знака от хеша влизат.
 *
 * 32 знака = 128 бита. Рожденият парадокс дава едно очаквано съвпадение при
 * ~2^64 отпечатъка — число, което няма как да се достигне от хора. Пълните 64
 * знака биха направили адреса нечетим, без да купят нищо: това не е защита
 * срещу нападател, който ИЗБИРА ключа си, защото такъв нападател така или
 * иначе получава свой собствен адрес, не чужд.
 */
export const ZNATSI_V_OTPECHATAKA = 32;

const SAMO_HEKS = /^[0-9a-f]+$/;

/**
 * Отпечатъкът от вече сметнат хеш на публичния ключ.
 *
 * Хешът се смята в адаптера (`src/nositel/`), защото там е `crypto.subtle`.
 * Тук стои само ФОРМАТЪТ — и той е чист код, тъй че тестът му не иска нито
 * браузър, нито часовник.
 */
export function otpechatakOtHesh(hesh: string): Otpechatak {
  if (!SAMO_HEKS.test(hesh) || hesh.length < ZNATSI_V_OTPECHATAKA) {
    throw new Error(
      `Отпечатъкът се строи от шестнайсетичен хеш с поне ${ZNATSI_V_OTPECHATAKA} знака; подаден е „${hesh}".`,
    );
  }
  return BELEG_NA_OTPECHATAK + hesh.slice(0, ZNATSI_V_OTPECHATAKA);
}

/** Вярна ли е формата на един отпечатък. */
export function eOtpechatak(s: string): boolean {
  if (!s.startsWith(BELEG_NA_OTPECHATAK)) return false;
  const opashka = s.slice(BELEG_NA_OTPECHATAK.length);
  return opashka.length === ZNATSI_V_OTPECHATAKA && SAMO_HEKS.test(opashka);
}

/**
 * КОГАТО САМОЛИЧНОСТ НЯМА · и защо това е стойност, а не изключение.
 *
 * `crypto.subtle` го има само в сигурен контекст. Липсва ли, приложението пак
 * трябва да тръгне — служебната книга не иска ключ. Но лична верига тогава НЕ
 * СЕ ПИШЕ, и това е по-добре от мълчалив отказ или от тихо разрешение.
 *
 * Стойността е нарочно такава, че НИКОГА да не съвпадне с истински адрес:
 * всеки истински отпечатък започва с `k1-`, тъй че `bez-samolichnost~lichno`
 * не може да бъде ничия лична верига. Тоест сравнението във Вратата дава
 * „не" по конструкция, не по забрава.
 */
export const BEZ_SAMOLICHNOST = 'bez-samolichnost';

/** Наставката на личната верига · ADR-024 §2. */
export const NASTAVKA_LICHNO = '~lichno';

/**
 * Адресът на личната верига.
 *
 * `k1-<32 знака>~lichno`. Не започва с името на служебната книга — това е
 * цялата защита и тя е по конструкция.
 */
export function verigaLichna(o: Otpechatak): string {
  if (!eOtpechatak(o)) {
    throw new Error(
      `Личната верига иска отпечатък във форма „${BELEG_NA_OTPECHATAK}…"; подаден е „${o}".`,
    );
  }
  return o + NASTAVKA_LICHNO;
}

/** Лична ли е тази верига. */
export function eLichnaVeriga(veriga: string): boolean {
  return veriga.endsWith(NASTAVKA_LICHNO) && eOtpechatak(veriga.slice(0, -NASTAVKA_LICHNO.length));
}

/**
 * Чий е този адрес · обратното на `verigaLichna`.
 *
 * Връща `undefined`, а не хвърля: пита се за ЧУЖДИ вериги, а чуждото може да
 * е какво ли не. Отказът тук е отговор, не изключение.
 */
export function otpechatakNaVeriga(veriga: string): Otpechatak | undefined {
  if (!eLichnaVeriga(veriga)) return undefined;
  return veriga.slice(0, -NASTAVKA_LICHNO.length);
}
