/**
 * Схемата на събитието — договорът, на който виси всичко останало.
 * System design §3.1. Еднаква за трите носителя (А Sheets+GAS · Б сървър · В местно-първо).
 */

import { NASTAVKA_LICHNO } from './samolichnost.js';

/** Върху коя същност действа събитието. */
export interface Sashtnost {
  /** вид: 'imot' | 'naem' | 'plashtane' | ... */
  readonly vid: string;
  readonly id: string;
}

/** Ключ за сравнение на същности. */
export function klyuchNaSashtnost(s: Sashtnost): string {
  return `${s.vid} ${s.id}`;
}

/**
 * КЛЮЧ НА ЕДНО ЗВЕНО · верига + seq, а не голо `seq`.
 *
 * Докато веригата беше една, `seq` сочеше еднозначно. Веригите станаха
 * няколко и **всяка тръгва от `seq 1`** — тоест голото число вече сочи по
 * едно събитие във ВСЯКА верига наведнъж.
 *
 * Цената, ако това се пропуснеше: сторно на seq 5 в моята верига щеше да
 * погаси seq 5 и в твоята, и в неговата. Тихо, без нито едно съобщение, и
 * само в сгънатото Огледало — тоест невидимо за всеки, който гледа своята
 * книга поотделно.
 */
export function klyuchNaZveno(s: KoyPishe & { readonly seq: number }): string {
  return zvenoNa(veriga(s), s.seq);
}

/**
 * Същият ключ, но от ГОТОВ низ на верига.
 *
 * Сторното сочи ЧУЖДО звено (`pogasyavaVeriga`) и там веригата идва като низ,
 * не като събитие. Двете влизаха в един и същи израз, писан на две места —
 * `naivno.ts` държеше свое копие. Един факт, един дом (правило 14).
 */
export function zvenoNa(veriga: string, seq: number): string {
  return `${veriga}#${seq}`;
}

/** Двете полета, от които се строи ключът на веригата. */
export interface KoyPishe {
  readonly kniga: string;
  readonly pisach: string;
}

/**
 * ЗАПАЗЕНАТА „книга" на ЛИЧНАТА верига · тя не е книга.
 *
 * Личното живее ИЗВЪН всяка книга — това е цялата защита и тя е по
 * конструкция, не по настройка (`samolichnost.ts` §„ЗАЩО НЕ ЗАПОЧВА С
 * `coretovia`"). Стойността не може да бъде име на файл: започва с
 * наставката, а не с буква.
 *
 * Домът ѝ е ЕДИН и е `samolichnost.ts` (правило 14): там наставката е
 * решение на ADR-024 §2 и там живее обяснението ѝ. Тук се внася, вместо да
 * се пише втори път — два еднакви низа на две места се разминават мълчаливо
 * точно в деня, в който единият се смени.
 */
const KNIGA_LICHNA = NASTAVKA_LICHNO;

/**
 * ЧИНЪТ НА САМАТА КНИГА · докато писачите са един.
 *
 * Служебната верига е на книгата, не на човек: първото събитие ражда
 * Стопанина (ADR-043) и още няма чий отпечатък да носи. Стойността е дума,
 * не празно — празното поле е забранено на Вратата и с право.
 */
export const PISACH_NA_KNIGATA = 'kniga';

/**
 * КЛЮЧЪТ НА ВЕРИГАТА · ЕДИНСТВЕНИЯТ дом на композицията (правило 14).
 *
 * Дотук композитният низ беше ПОЛЕ и носеше три смисъла наведнъж — книга,
 * писач и устройство (Т39). Сега трите са отделни полета, а низът е
 * ИЗВЕДЕН: Дневникът пази редиците под ключ, и това си остава негова
 * работа, но нито един смисъл вече не се вади с рязане на низ извън тук.
 *
 * Трите случая, изчерпателно:
 *
 *   лична          `k1-…~lichno`        книгата е `KNIGA_LICHNA`
 *   на книгата     `coretovia`          писачът е `PISACH_NA_KNIGATA`
 *   на писач       `coretovia~k1-…`     всичко останало
 */
export function veriga(s: KoyPishe): string {
  if (s.kniga === KNIGA_LICHNA) return s.pisach + KNIGA_LICHNA;
  return s.pisach === PISACH_NA_KNIGATA ? s.kniga : `${s.kniga}~${s.pisach}`;
}

/**
 * ОБРАТНОТО · от готов низ обратно към двата факта.
 *
 * Стои ТУК, до `veriga`, а не където дотрябва: композицията и разлагането ѝ
 * са едно правило и два дома за него значи два начина да се разминат
 * (правило 14). Всеки, който реже низ на верига извън този файл, строи
 * втория дом.
 *
 * `veriga(koyPishe(x)) === x` за всеки низ, роден от `veriga` — това е
 * договорът и той се доказва с тест, не се обещава в коментар.
 */
export function koyPishe(v: string): KoyPishe {
  if (v.endsWith(KNIGA_LICHNA)) {
    return { kniga: KNIGA_LICHNA, pisach: v.slice(0, -KNIGA_LICHNA.length) };
  }
  const i = v.indexOf('~');
  return i < 0
    ? { kniga: v, pisach: PISACH_NA_KNIGATA }
    : { kniga: v.slice(0, i), pisach: v.slice(i + 1) };
}

/**
 * СЪРЦЕВИНАТА · каквото операцията и събитието носят ЕДНАКВО.
 *
 * Кой (`actor`), в коя книга и по чия верига, какво (`type` · `payload`), над коя
 * същност и кога. Написани два пъти, тези седем полета се разминават:
 * добавено поле на входа и забравено в записа минава компилацията и стига до
 * Журнала само наполовина.
 *
 * Затова НЕ е `Sabitie extends Operatsiya`, колкото и да изглежда така.
 * `expectedRev` е rev-предпазител НА ВХОДА и не влиза в Журнала — с `extends`
 * той тихо ставаше позволено поле на записаното събитие и на `ZaHeshirane`.
 * Разликата между вход и запис е точно онова, което този тип пази.
 */
interface Sarzevina {
  /** uuid на операцията — носи идемпотентността */
  readonly opId: string;
  /** ISO време, една зона (UTC) */
  readonly ts: string;
  /**
   * ВАЛУТАТА, в която е писано събитието.
   *
   * Негово, 09.09: „**За парите се избира една валута в началото при
   * регистрация.**" Една Книга — една валута; втората е ПЛАТЕНА добавка, като
   * езиците, и курс НЯМА (правило 3).
   *
   * Стои в подписа на ВСЯКО събитие, не само на паричните, и то нарочно:
   * така внесен чужд Журнал не може да бъде тихо преномериран в друга валута.
   * Смяна на валутата тогава е ВИДИМО ново събитие, не преразказ на историята.
   */
  readonly valuta: string;
  /**
   * КОЯ КНИГА · един файл = една фирма (негово, 09.09: „Това даже не са
   * проекти, а втори файл… Един вид като в Ексел да отвориш нов файл.").
   *
   * Изолацията виси на това поле и на нищо друго. `KNIGA_LICHNA` е
   * запазената стойност за личната верига — тя НЕ е книга и по конструкция
   * не попада в обхвата на никоя.
   */
  readonly kniga: string;
  /**
   * КОЙ ПИСАЧ · неговата верига (правило 6: всеки писач е своя верига).
   *
   * Днес стойността е `PISACH_NA_KNIGATA` — чинът на самата Книга, — защото
   * писачите са един и първото събитие тепърва ражда Стопанина (ADR-043).
   * Станат ли повече, тук влиза отпечатъкът на човека и всеки получава своя
   * верига, без нито един стар запис да се пипа.
   */
  readonly pisach: string;
  /**
   * ОТ КОЕ УСТРОЙСТВО е дошло събитието · отпечатъкът `k1-…`.
   *
   * Това е СВОЙ факт, не украса: днес писачът е книгата, а устройството е
   * машината — и в мига, в който един човек отвори втора машина, разликата
   * вече е ЗАПИСАНА, вместо да се добавя върху подписани събития (правило 1
   * не прощава закъснели огради).
   *
   * Слепването на трите в една дума беше точно дефектът, който Т39 намери.
   */
  readonly ustroystvo: string;
  /** имейл на извършителя — самоличност */
  readonly actor: string;
  /** 'НаемДобавен' | 'ПлащанеПрието' | 'Сторно' | ... */
  readonly type: string;
  readonly sashtnost: Sashtnost;
  readonly payload: Readonly<Record<string, unknown>>;
}

/** Операция, подадена на Вратата. Още не е събитие — може да бъде отказана. */
export interface Operatsiya extends Sarzevina {
  /**
   * rev-предпазител: seq на последното събитие за тази същност, което си видял.
   * Пропуснато = без проверка (нови същности, миграции).
   *
   * САМО НА ВХОДА. Вратата строи записа поле по поле и не го пренася — той
   * казва какво си ВИДЯЛ, не какво е СТАНАЛО.
   */
  readonly expectedRev?: number;
}

/**
 * Записано събитие. Само за четене — Журналът е само за добавяне.
 * Полетата за пари в payload завършват на `_st` и са цели центове.
 */
export interface Sabitie extends Sarzevina {
  /**
   * ВЕРСИЯТА НА СХЕМАТА · кой договор е валиден за ТОВА събитие.
   *
   * Дотук я нямаше, и това беше необратим риск: Журналът е само за добавяне,
   * тъй че вчерашният запис не може да се пренапише — може само да се ЧЕТЕ.
   * Без номер вътре в самия запис четецът гадае по наличието на полета, а
   * гадаенето върху пари е дефект.
   *
   * Числото се вдига, когато СМИСЪЛЪТ на поле се смени, не когато се добави
   * ново. Стар номер не се приема мълчаливо: той получава думи (`hash.ts`).
   */
  readonly shema: number;
  /** цяло, монотонно В РАМКИТЕ НА ЕДНА ВЕРИГА (книга + писач) */
  readonly seq: number;
  /** хеш на предишното събитие в СЪЩАТА верига; празен низ за първото */
  readonly prevHash: string;
  readonly hash: string;
}

/** Полетата, които влизат в хеша — всичко без самия хеш. */
export type ZaHeshirane = Omit<Sabitie, 'hash'>;

/**
 * ДНЕШНАТА версия на схемата · пише се във всяко ново събитие.
 *
 * 1 · първата, която НОСИ номера си · книга · писач · устройство · валута
 *
 * Преди нея имаше записи без номер; те се разпознават по подписа си
 * (`predi-razreza` в `hash.ts`) и не се приемат мълчаливо.
 */
export const SHEMA = 1;

/**
 * ВЕРСИЯ 0 · записите ОТПРЕДИ разреза · и защо изобщо съществува тук.
 *
 * Те нямат поле `shema` — нямаха и как. Затова липсващата версия СЕ ЧЕТЕ като
 * нула, а не като „днешната": нула казва „подписан е по стария ред" и точно
 * по това `hash.ts` избира с коя канонична форма да го провери.
 *
 * Така стар запис минава като ЦЯЛ, вместо да се обявява за счупен. Това е
 * цялата причина полето да съществува (правило 1: вчерашният запис не се
 * пренаписва — чете се).
 */
export const SHEMA_PREDI_RAZREZA = 0;

/**
 * СТОЙНОСТТА, която казва „този факт го НЯМАШЕ, когато записът е писан".
 *
 * Стар запис няма нито устройство, нито валута. Пренасянето НЕ ги измисля:
 * да сложиш „EUR" на запис, писан преди валутата да съществува, е да
 * съчиниш факт за пари. Тук стои дума, която не може да бъде объркана със
 * стойност — и това е правило 12, приложено към данните, не към екрана.
 *
 * Полето е ИЗВЪН подписа на такъв запис (версия 0 не го включва), тъй че
 * стойността не мени нито един хеш.
 */
export const PREDI_RAZREZA = 'predi-razreza';

/**
 * ДВЕТЕ ВАЛУТИ · негово, 09.09: избира се ЕДНА при регистрация.
 *
 * Курс между тях НЯМА и сбор през две валути е ОТКАЗ, не тихо число
 * (правило 3). Втората валута е платена добавка, като езиците.
 */
export const VALUTI = Object.freeze(['EUR', 'USD'] as const);
export type Valuta = (typeof VALUTI)[number];
